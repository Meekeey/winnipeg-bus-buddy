export type IconName = keyof typeof ICONS;

type Props = {
  name: IconName;
  size?: number; // width in CSS pixels
  rotate?: number; // degrees (the arrow points right by default)
  className?: string;
};

export function PixelIcon({ name, size = 24, rotate = 0, className }: Props) {
  const rows = ICONS[name];
  const columns = rows[0].length;
  const squares = [];
  for (let y = 0; y < rows.length; y++) {
    for (let x = 0; x < columns; x++) {
      if (rows[y][x] === "#") {
        squares.push(<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} />);
      }
    }
  }
  return (
    <svg
      className={className}
      width={size}
      height={(size * rows.length) / columns}
      viewBox={`0 0 ${columns} ${rows.length}`}
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden="true"
      style={rotate ? { transform: `rotate(${rotate}deg)` } : undefined}
    >
      {squares}
    </svg>
  );
}
